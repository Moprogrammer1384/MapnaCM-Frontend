function readCatalog(filePath) {
  const source = fs.readFileSync(filePath, 'utf8');
  const json = source
    .replace(/^\s*\/\*[\s\S]*?\*\/\s*/, '')
    .replace(/^\s*\/\/.*$/gm, '')
    .replace(/^\s*export\s+default\s+/, '')
    .replace(/;\s*$/, '');
  return JSON.parse(json);
}

function ensureSafeGeneratedDirectory(directoryPath) {
  const resolvedWorkspace = path.resolve(workspaceRoot);
  const resolvedDirectory = path.resolve(directoryPath);
  if (!resolvedDirectory.startsWith(`${resolvedWorkspace}${path.sep}`)) {
    throw new Error(`Refusing to generate outside the workspace: ${resolvedDirectory}`);
  }
  if (fs.existsSync(resolvedDirectory)) {
    const marker = path.join(resolvedDirectory, '.apache-echarts-generated');
    const entries = fs.readdirSync(resolvedDirectory);
    if (!fs.existsSync(marker) && entries.length > 0) {
      throw new Error(`Refusing to replace an unmarked directory: ${resolvedDirectory}`);
    }
    fs.rmSync(resolvedDirectory, { recursive: true, force: true });
  }
  fs.mkdirSync(resolvedDirectory, { recursive: true });
  fs.writeFileSync(
    path.join(resolvedDirectory, '.apache-echarts-generated'),
    'Generated by tools/generate-apache-echarts.mjs.\n'
  );
}

function pascalCase(value) {
  const result = value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join('');
  return /^\d/.test(result) ? `Demo${result}` : result;
}

function selectorFor(id) {
  return `app-apache-widget-${id}`
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-');
}

function componentFileName(id) {
  return `${id.split('/').at(-1)}-apache-widget.component.ts`;
}

function componentClassName(id) {
  return `${pascalCase(id)}ApacheWidgetComponent`;
}

function displayTitle(demo) {
  if (demo.title) {
    return demo.title;
  }
  return demo.id
    .split('/')
    .at(-1)
    .split(/[-_]+/)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join(' ');
}

