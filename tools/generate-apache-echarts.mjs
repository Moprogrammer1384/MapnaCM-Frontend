function compileExample(sourceCode, fileName, demoId) {
  const extension = path.extname(fileName).toLowerCase();
  let output = sourceCode;
  if (extension === '.ts') {
    const browserSource = sourceCode
      .replace(/^\s*import[\s\S]*?from\s+['"]echarts['"];?\s*$/gm, '')
      .replace(/^\s*export\s*\{\s*\};?\s*$/gm, '');
    const result = ts.transpileModule(browserSource, {
      fileName,
      reportDiagnostics: true,
      compilerOptions: {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.None,
        removeComments: false,
        sourceMap: false,
      },
    });
    const errors = (result.diagnostics ?? []).filter(
      (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error
    );
    if (errors.length > 0) {
      const message = ts.formatDiagnosticsWithColorAndContext(errors, {
        getCanonicalFileName: (name) => name,
        getCurrentDirectory: () => sourceRoot,
        getNewLine: () => '\n',
      });
      throw new Error(`Unable to transpile ${fileName}:\n${message}`);
    }
    output = result.outputText;
  }

  output = output
    .replace(/^\s*import[\s\S]*?from\s+['"]echarts['"];?\s*$/gm, '')
    .replace(/^\s*export\s*\{\s*\};?\s*$/gm, '')
    .trim();

  for (const [from, to] of examplePatches.get(demoId) ?? []) {
    if (!output.includes(from)) {
      throw new Error(`Legend patch for ${demoId} no longer applies:
${from}`);
    }
    output = output.split(from).join(to);
  }

  // Match the official editor's execution wrapper and fail generation on syntax errors.
  new Function(
    'myChart',
    'app',
    'setTimeout',
    'setInterval',
    'ROOT_PATH',
    'CDN_PATH',
    'echarts',
    '$',
    'ecStat',
    'document',
    'window',
    `var option, css;\n${output}\nreturn [option, css];`
  );

  return `/*\n * Adapted from Apache ECharts examples (${sourceCommit}).\n * Licensed under the Apache License 2.0.\n * Source: https://github.com/apache/echarts-examples\n */\n${output}\n`;
}

