const imports = [];
const entries = [];
const classNames = new Set();
const selectors = new Set();

for (const demo of demos) {
  const extension = demo.ts ? '.ts' : '.js';
  const sourceFile = path.join(sourceRoot, `${demo.id}${extension}`);
  if (!fs.existsSync(sourceFile)) {
    throw new Error(`Missing source for ${demo.id}: ${sourceFile}`);
  }

  const className = componentClassName(demo.id);
  const selector = selectorFor(demo.id);
  if (classNames.has(className) || selectors.has(selector)) {
    throw new Error(`Generated component name collision for ${demo.id}`);
  }
  classNames.add(className);
  selectors.add(selector);

  const widgetDirectory = path.join(generatedRoot, ...demo.id.split('/'));
  fs.mkdirSync(widgetDirectory, { recursive: true });
  const widgetFile = componentFileName(demo.id);
  const relativeToChartRoot = path.relative(widgetDirectory, path.dirname(generatedRoot));
  const componentImport = path
    .join(relativeToChartRoot, 'Apache-Echarts/apache-echarts.component')
    .replaceAll('\\', '/');

  const componentSource = `import { Component } from '@angular/core';
import { ApacheEchartsComponent } from '${componentImport.startsWith('.') ? componentImport : `./${componentImport}`}';

@Component({
  selector: '${selector}',
  standalone: true,
  imports: [ApacheEchartsComponent],
  template: \`<app-apache-echarts [demoId]="demoId" height="420px"></app-apache-echarts>\`,
})
export class ${className} {
  readonly demoId = ${JSON.stringify(demo.id)};
}
`;
  fs.writeFileSync(path.join(widgetDirectory, widgetFile), componentSource);

  const outputFile = path.join(examplesRoot, `${demo.id}.js`);
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  const compiled = compileExample(
    fs.readFileSync(sourceFile, 'utf8'),
    sourceFile,
    demo.id
  );
  fs.writeFileSync(outputFile, compiled);

  const importPath = `./${demo.id}/${widgetFile.replace(/\.ts$/, '')}`;
  imports.push(`import { ${className} } from '${importPath}';`);
  entries.push(`  {
    id: ${JSON.stringify(demo.id)},
    title: ${JSON.stringify(displayTitle(demo))},
    titleCN: ${JSON.stringify(demo.titleCN ?? '')},
    categories: ${JSON.stringify(demo.category)},
    difficulty: ${Number(demo.difficulty ?? 0)},
    since: ${demo.since ? JSON.stringify(demo.since) : 'undefined'},
    component: ${className},
  }`);
}

const registry = `import { Type } from '@angular/core';
${imports.join('\n')}

export interface ApacheEchartsDemo {
  readonly id: string;
  readonly title: string;
  readonly titleCN: string;
  readonly categories: readonly string[];
  readonly difficulty: number;
  readonly since?: string;
  readonly component: Type<unknown>;
}

export const APACHE_ECHARTS_DEMOS: readonly ApacheEchartsDemo[] = [
${entries.join(',\n')}
];
`;
fs.writeFileSync(registryPath, registry);

